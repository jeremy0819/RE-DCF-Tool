# 都更全案投報——成本率預設（來源：安和段估價師級共負試算＋都更權利變換實施辦法六大科目）
# 各案範本可覆寫此處任一項；新案沿用此預設。比率為「萬元」制（單價萬/坪、金額萬元）。
