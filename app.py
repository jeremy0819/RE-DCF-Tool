# L6 都更全案投報層：總銷 → 共同負擔六大科目 → 分回 → 報酬率 → 敏感度
# 法源：都市更新權利變換實施辦法「費用負擔」六類（工程/權變/利息/稅捐/管理/其他）。
# 參數基準：安和段估價師級共負試算（2025 送審版）。純函式、無 Streamlit，可被測試引用。
# 對應建築師 Excel 的「坪效及獲利分析」分頁，供開啟舊表逐格對照。
