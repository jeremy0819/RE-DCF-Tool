# P1 更新前價值估算（L7 權利變換基準）
# 法源：都市更新條例 §56 — 權利變換以「更新前各宗土地及建物現值」為基礎計算比例。
# ===========================================================================
def calc_更新前價值(基地面積, 地價_萬坪, 既有建物面積=0.0, 建物單價=0.0,
                   屋齡=0, 折舊率=0.02) -> dict:
    """
    更新前土地 + 建物現值估算。
      土地現值 = 基地坪 × 地價（萬/坪）
      建物現值 = 建物坪 × 建物單價 × 殘值率
      殘值率   = max(0, 1 − 折舊率 × 屋齡)　RC 造法定折舊 2%/年（耐用年限 50 年）
    回傳值作為權利變換「各地主更新前貢獻比例」的分母基準。
    """
    基地坪 = 基地面積 / 平方米換坪
    土地現值 = 基地坪 * 地價_萬坪
    建物殘值率 = max(0.0, 1.0 - 折舊率 * 屋齡)
    建物坪 = 既有建物面積 / 平方米換坪
    建物現值 = 建物坪 * 建物單價 * 建物殘值率
    更新前總值 = 土地現值 + 建物現值
    return {
        "基地坪": 基地坪,
        "土地現值": 土地現值,
        "建物坪": 建物坪,
        "建物現值": 建物現值,
        "建物殘值率": 建物殘值率,
        "更新前總值": 更新前總值,
    }


